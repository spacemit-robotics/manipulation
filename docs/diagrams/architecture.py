class Diagram:
    """Small SVG primitives; all architecture labels and geometry live in render()."""

    def __init__(self):
        self.items = []

    def text(self, x, y, value, size=18, color="#475569", weight=400, anchor="middle"):
        self.items.append(
            f'<text x="{x}" y="{y}" font-size="{size}" fill="{color}" '
            f'font-weight="{weight}" text-anchor="{anchor}">{escape(value)}</text>'
        )

    def rect(self, x, y, width, height, kind, fill=None):
        stroke, background = COLORS[kind]
        self.items.append(
            f'<rect x="{x}" y="{y}" width="{width}" height="{height}" rx="10" '
            f'fill="{fill or background}" stroke="{stroke}" stroke-width="1.5"/>'
        )

    def box(self, x, y, width, height, title, lines, kind, size=18):
        self.rect(x, y, width, height, kind)
        line_height = 25
        first = y + height / 2 - len(lines) * line_height / 2 + 7
        self.text(x + width / 2, first, title, 21, "#1f2937", 600)
        for index, line in enumerate(lines, 1):
            self.text(x + width / 2, first + index * line_height, line, size)

    def arrow(self, points, data=False):
        color = "#287b70" if data else "#475569"
        dash = ' stroke-dasharray="6 5"' if data else ""
        marker = "data" if data else "call"
        self.items.append(
            f'<path d="{points}" fill="none" stroke="{color}" stroke-width="1.8"'
            f'{dash} marker-end="url(#{marker})"/>'
        )

    def output(self):
        body = "\n    ".join(self.items)
        return (
            '<svg xmlns="http://www.w3.org/2000/svg" width="1180" height="1340" '
            'viewBox="0 0 1180 1340" role="img" aria-labelledby="title desc">\n'
            '  <!-- Generated by docs/diagrams/architecture.py; edit that source. -->\n'
            '  <title id="title">manipulation 组件架构</title>\n'
            f'  <desc id="desc">{escape(DESCRIPTION)}</desc>\n'
            '  <defs>\n'
            '    <marker id="call" markerWidth="8" markerHeight="8" refX="8" refY="4" '
            'orient="auto" markerUnits="userSpaceOnUse">'
            '<path d="M0 0 L8 4 L0 8 Z" fill="#475569"/></marker>\n'
            '    <marker id="data" markerWidth="8" markerHeight="8" refX="8" refY="4" '
            'orient="auto" markerUnits="userSpaceOnUse">'
            '<path d="M0 0 L8 4 L0 8 Z" fill="#287b70"/></marker>\n'
            '  </defs>\n'
            '  <rect width="1180" height="1340" fill="#ffffff"/>\n'
            '  <g font-family="Noto Sans CJK SC, Source Han Sans SC, '
            'PingFang SC, Microsoft YaHei, sans-serif">\n'
            f'    {body}\n'
            '  </g>\n'
            '</svg>\n'
        )


