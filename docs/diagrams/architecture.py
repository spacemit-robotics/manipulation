def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--docs-ros", type=Path, help="also update/check the Chinese SVG in this docs-ros checkout")
    parser.add_argument("--check", action="store_true", help="fail if either selected SVG differs from the source")
    args = parser.parse_args()
    targets = [SDK_IMAGE]
    if args.docs_ros is not None:
        target = args.docs_ros.resolve() / ROS_IMAGE
        if not target.is_file():
            parser.error(f"docs-ros architecture image not found: {target}")
        targets.append(target)
    content = render().encode("utf-8")
    if args.check:
        stale = [path for path in targets if not path.is_file() or path.read_bytes() != content]
        for path in stale:
            print(f"out of date: {path}", file=sys.stderr)
        return 1 if stale else 0
    for path in targets:
        path.write_bytes(content)
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
