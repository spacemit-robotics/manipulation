class Diagram:
    """Small SVG primitives; all architecture labels and geometry live in render()."""

    def __init__(self):
        self.items = []

    def text(self, x, y, value, size=14, color="#4b5563", weight=400, anchor="middle"):
        self.items.append(
            f'<text x="{x:g}" y="{y:g}" font-size="{size}" fill="{color}" '
            f'font-weight="{weight}" text-anchor="{anchor}">{escape(value)}</text>'
        )

    def rect(self, x, y, width, height, kind, panel=False, dashed=False):
        stroke, background = COLORS[kind]
        dash = ' stroke-dasharray="6 4"' if dashed else ""
        self.items.append(
            f'<rect class="box" x="{x:g}" y="{y:g}" width="{width:g}" height="{height:g}" '
            f'rx="{10 if panel else 8}" fill="{background if panel else "#ffffff"}" '
            f'stroke="{stroke}" stroke-opacity="{0.35 if panel else 0.75}" '
            f'stroke-width="{1.2 if panel else 1.5}"{dash}/>'
        )

    def layer(self, y, height, title, kind, detail="", right=MAIN_RIGHT):
        self.rect(LEFT, y, right - LEFT, height, kind, panel=True)
        self.items.append(
            f'<path d="M{LEFT + 10} {y} H{LEFT + LABEL_WIDTH} V{y + height} '
            f'H{LEFT + 10} Q{LEFT} {y + height} {LEFT} {y + height - 10} '
            f'V{y + 10} Q{LEFT} {y} {LEFT + 10} {y} Z" '
            f'fill="{COLORS[kind][0]}" fill-opacity="0.12"/>'
        )
        middle = y + height / 2
        self.text(LEFT + LABEL_WIDTH / 2, middle + (-2 if detail else 6),
                  title, 16, COLORS[kind][0], 700)
        if detail:
            self.text(LEFT + LABEL_WIDTH / 2, middle + 19, detail, 12.5, "#6b7280")

    def box(self, x, y, width, height, title, lines, kind, size=14):
        self.rect(x, y, width, height, kind)
        first = y + (height - 17 - len(lines) * 20) / 2 + 14
        self.text(x + width / 2, first, title, 17, "#1f2937", 600)
        for index, line in enumerate(lines):
            self.text(x + width / 2, first + 22 + index * 20, line, size)

    def arrow(self, points, data=False):
        color = COLORS["support"][0] if data else "#475569"
        dash = ' stroke-dasharray="6 5"' if data else ""
        marker = "data" if data else "call"
        self.items.append(
            f'<path d="{points}" fill="none" stroke="{color}" stroke-width="1.7"'
            f'{dash} marker-end="url(#{marker})"/>'
        )

    def output(self):
        body = "\n    ".join(self.items)
        return (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" '
            f'viewBox="0 0 {WIDTH} {HEIGHT}" role="img" aria-labelledby="title desc">\n'
            '  <!-- Generated by docs/diagrams/architecture.py; edit that source. -->\n'
            '  <title id="title">manipulation 组件架构</title>\n'
            f'  <desc id="desc">{escape(DESCRIPTION)}</desc>\n'
            '  <defs>\n'
            '    <marker id="call" markerWidth="8" markerHeight="8" refX="8" refY="4" '
            'orient="auto" markerUnits="userSpaceOnUse">'
            '<path d="M0 0 L8 4 L0 8 Z" fill="#475569"/></marker>\n'
            '    <marker id="data" markerWidth="8" markerHeight="8" refX="8" refY="4" '
            'orient="auto" markerUnits="userSpaceOnUse">'
            '<path d="M0 0 L8 4 L0 8 Z" fill="#2f8a57"/></marker>\n'
            '  </defs>\n'
            f'  <rect width="{WIDTH}" height="{HEIGHT}" fill="#ffffff"/>\n'
            '  <g font-family="Noto Sans CJK SC, Source Han Sans SC, '
            'PingFang SC, Microsoft YaHei, sans-serif">\n'
            f'    {body}\n'
            '  </g>\n'
            '</svg>\n'
        )


